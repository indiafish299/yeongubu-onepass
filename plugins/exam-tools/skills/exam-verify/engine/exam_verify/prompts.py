PROOF = _HEAD + """
너는 인쇄 직전 시험지의 교정자다. 아래 [글자 층]은 같은 시험지 PDF 에서 기계로 뽑은 글이다.
한 글자씩 읽어라. 뜻이 통하도록 알아서 고쳐 읽지 마라. 찾을 것:
- 오탈자(없는 낱말, 글자가 바뀌거나 빠지거나 겹친 곳), 조사·어미가 틀린 곳
- 단위·기호·화학식·첨자 표기 오류, 같은 용어를 다르게 적은 곳
- 문항 번호·보기 번호(①~⑤, ㄱㄴㄷ)가 빠지거나 겹친 곳
글자 층을 뽑으면서 생긴 것(수식이 깨짐, 줄 순서가 뒤섞임, 글자 사이 공백, 가린 칸의 빈자리)은 오류가 아니다.
의심되는 곳은 쪽 이미지에서 그 자리를 찾아 실제로 그렇게 인쇄됐는지 확인하고, 인쇄된 대로인 것만 적어라.
띄어쓰기 취향, 문체 다듬기, 문제 내용의 옳고 그름은 적지 마라. 없으면 빈 목록을 내라.

[글자 층]
{text}
""" + _JSON + """
{{"issues": [{{"q": "4", "quote": "틀린 글귀를 인쇄된 그대로", "fix": "고친 글귀", "why": "한 문장", "confidence": "high|mid|low"}}]}}
"""


def fill(tpl: str, pages: list, **kw) -> str:
    names = ", ".join(p.name for p in pages)
    return tpl.format(pages=names, **SEVERITY, **kw)
